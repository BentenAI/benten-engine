    // The outbound wire is the byte-faithful IETF LAMPS layout
    // `mldsaSig(3309) || tradSig(64)` — ML-DSA FIRST, total 3373 B, NO
    // commitment trailer — and Benten's OWN inbound surface round-trips it.
    let suite = SignatureSuite::v1_default();
    let kp = suite.generate_keypair();
    let msg = b"benten-lamps-outbound-wire-roundtrip";
    let live_sig = suite.sign(&kp, msg);
    let wire = live_sig.to_wire_bytes();
