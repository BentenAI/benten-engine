/// F-KAT-4 (a-AUTHENTIC) — the REAL IETF LAMPS vector's Ed25519 half
/// cryptographically verifies against the real LAMPS `M'`, using Benten's own
/// `ed25519-dalek` + `sha2` deps. **Always-running, non-sentinel.**
///
/// This is the genuine cross-ecosystem-bytes check that the corpus IS in-tree
/// and authentic. It proves: (1) the embedded fixture bytes are the real
/// published LAMPS WG bytes (any tampered byte FAILS this); (2) the LAMPS `M'`
/// construction (`Prefix || Label || len(ctx)||ctx || SHA-512(M)`) is correctly
/// reconstructed; (3) Benten's classical primitive validates the classical leg
/// of a real IETF composite. It does NOT claim Benten's *composite* verifier
/// accepts the *whole* composite (that is the named-deferred FORMAT-GAP work).
///
/// would-FAIL-if-no-op'd: a flipped byte of `ED25519_SIG`/`ED25519_PK`, a wrong
/// Prefix/Label, or a wrong pre-hash would make the Ed25519 verify reject.
#[test]
fn real_lamps_vector_ed25519_half_is_authentic() {
    use benten_crypto_suite::primitives::ed25519_dalek::{Signature, Verifier as _, VerifyingKey};

    let vk = VerifyingKey::from_bytes(&real_lamps_vector::ED25519_PK)
        .expect("real LAMPS vector Ed25519 public-key half MUST be a valid Ed25519 point");
    let sig = Signature::from_bytes(&real_lamps_vector::ED25519_SIG);
    let m_prime = real_lamps_vector::m_prime();

    vk.verify(&m_prime, &sig).expect(
        "the Ed25519 (traditional) half of the REAL IETF LAMPS \
         id-MLDSA65-Ed25519-SHA512 vector MUST verify against the reconstructed \
         LAMPS M' — proves the embedded cross-ecosystem fixture is authentic \
         published bytes, not a synthesized sentinel",
    );

    // Pin the published composite shape (mldsaSig(3309)||tradSig(64) etc.) so
    // the LAMPS serialization order is locked alongside the crypto check.
    assert_eq!(real_lamps_vector::FULL_COMPOSITE_SIG_LEN, 3373);
    assert_eq!(real_lamps_vector::FULL_COMPOSITE_PK_LEN, 1984);
    assert_eq!(
        real_lamps_vector::TRAD_SIG_OFFSET,
        3309,
        "LAMPS serializes mldsaSig(3309) FIRST then tradSig — the Ed25519 half \
         begins at offset 3309 in the composite signature"
    );
    assert_eq!(real_lamps_vector::TRAD_PK_OFFSET, 1952);
}

/// F-KAT-4 (a) — INBOUND: Benten's PRODUCTION verifier ACCEPTS the REAL
/// published IETF LAMPS WG `id-MLDSA65-Ed25519-SHA512` composite signature
/// (the cross-ecosystem KAT that BouncyCastle / OpenSSL-3.5 / OpenPGP-PQC all
/// conform to — it is the WG's own known-answer test).
///
/// **CLOSED + LIVE (was NAMED-DEFERRED).** The prior FORMAT-GAP blocker is
/// resolved by the byte-faithful IETF LAMPS re-impl (`sig-lamps-faithful`,
/// Ben-ratified option A 2026-06-05): `SignatureSuite` now emits + accepts the
/// IETF LAMPS composite WIRE (`mldsaSig(3309) || tradSig(64)`, ML-DSA first,
/// shared `M'` with `mldsa_ctx = Label`, NO SHA3-256 commitment trailer). This
/// test reconstructs the FULL real composite pk (`mldsaPK(1952) || tradPK(32)`)
/// + sig (`mldsaSig(3309) || tradSig(64)`) from the embedded real published
/// bytes ([`real_lamps_vector::composite_pubkey`] /
/// [`real_lamps_vector::composite_sig`]) and drives the **LIVE production
/// verifier** [`benten_crypto_suite::sig::SignatureSuite::verify`] — which
/// ACCEPTS it (both halves cryptographically verify against the reconstructed
/// `M'`).
///
/// This is a genuine cross-ecosystem-bytes acceptance — NOT a synthesized
/// sentinel. would-FAIL-if-no-op'd: a flipped byte of the embedded composite
/// pk/sig, a wrong `M'` (Prefix/Label/pre-hash), an empty-ctx ML-DSA verify
/// (the spike's control), or any single-half-only accept regression.
#[test]
fn benten_accepts_cross_ecosystem_lamps_signatures() {
    use benten_crypto_suite::sig::{HybridSignature, PublicKey, SignatureSuite};

    let pk = PublicKey::from_lamps_composite_bytes(&real_lamps_vector::composite_pubkey())
        .expect("the REAL published composite pubkey (mldsaPK||tradPK) MUST parse");
    let sig = HybridSignature::from_lamps_composite_wire(&real_lamps_vector::composite_sig())
        .expect("the REAL published composite sig (mldsaSig||tradSig) MUST parse");

    let suite = SignatureSuite::v1_default();

    // The published `s` field is the EMPTY-ctx signature: verify with ctx = b"".
    suite
        .verify_with_context(
            pk.clone(),
            real_lamps_vector::MESSAGE,
            real_lamps_vector::CTX,
            &sig,
        )
        .expect(
            "Benten's PRODUCTION verifier MUST ACCEPT the REAL published IETF LAMPS \
             id-MLDSA65-Ed25519-SHA512 composite signature (cross-ecosystem interop; NQ-C3) — \
             both the ML-DSA-65 context-verify (mldsa_ctx=Label) and the Ed25519 verify pass \
             against the reconstructed shared M'. This is the byte-faithful IETF LAMPS wire.",
        );

    // Negative control: the SAME composite under a WRONG (non-empty) ctx MUST
    // fail closed — proves the M' (and thus the ctx) is load-bearing, not ignored.
    let wrong_ctx = b"a-different-application-context";
    assert!(
        suite
            .verify_with_context(pk.clone(), real_lamps_vector::MESSAGE, wrong_ctx, &sig)
            .is_err(),
        "the empty-ctx composite MUST FAIL closed under a wrong ctx — the LAMPS M' binds the ctx"
    );

    // Negative control: a tampered message MUST fail closed.
    assert!(
        suite
            .verify_with_context(
                pk,
                b"The quick brown fox jumps over the lazy dox.",
                real_lamps_vector::CTX,
                &sig
            )
            .is_err(),
        "a tampered message MUST FAIL the composite verify closed (M' carries SHA-512(M))"
    );
}

